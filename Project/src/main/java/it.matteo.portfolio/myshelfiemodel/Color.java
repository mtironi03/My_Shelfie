package myshelfiemodel;

/**
 * L'enumerazione Color rappresenta tutti i colori delle tessere presenti nel gioco.
 * Viene utilizzata per identificare in modo univoco la tipologia delle tessere (Tile) 
 * all'interno del tabellone centrale e delle librerie personali dei giocatori.
 */
public enum Color {

    PINK,
    BLUE,
    LIGHT_BLUE,
    GREEN,
    YELLOW,
    WHITE

}
